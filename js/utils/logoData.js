export function createExtrudedLogoGeometry(id) {
  const data = LOGO_DATA[id];
  if (!data) return new THREE.BoxGeometry(2, 2, 0.2);

  const { gridW, gridH, width, height, depth, mask: rows } = data;
  const cellW = width / gridW;
  const cellH = height / gridH;
  const halfD = depth / 2;

  // Flatten rows to boolean array
  const mask = new Uint8Array(gridW * gridH);
  for (let y = 0; y < gridH; y++) {
    const row = rows[y];
    for (let x = 0; x < gridW; x++) {
      if (row[x] === '1') mask[y * gridW + x] = 1;
    }
  }

  const rimPositions = [];
  const rimNormals = [];
  const rimUvs = [];

  const frontPositions = [];
  const frontNormals = [];
  const frontUvs = [];

  const backPositions = [];
  const backNormals = [];
  const backUvs = [];

  function addQuad(targetPos, targetNorm, targetUv, p0, p1, p2, p3, norm, uv0, uv1, uv2, uv3) {
    targetPos.push(
      p0[0], p0[1], p0[2],
      p1[0], p1[1], p1[2],
      p2[0], p2[1], p2[2],
      p0[0], p0[1], p0[2],
      p2[0], p2[1], p2[2],
      p3[0], p3[1], p3[2]
    );
    for (let i = 0; i < 6; i++) {
      targetNorm.push(norm[0], norm[1], norm[2]);
    }
    targetUv.push(
      uv0[0], uv0[1],
      uv1[0], uv1[1],
      uv2[0], uv2[1],
      uv0[0], uv0[1],
      uv2[0], uv2[1],
      uv3[0], uv3[1]
    );
  }

  for (let y = 0; y < gridH; y++) {
    for (let x = 0; x < gridW; x++) {
      if (!mask[y * gridW + x]) continue;

      const x0 = x * cellW - width / 2;
      const x1 = (x + 1) * cellW - width / 2;
      const y1 = height / 2 - y * cellH;
      const y0 = height / 2 - (y + 1) * cellH;

      const u0 = x / gridW;
      const u1 = (x + 1) / gridW;
      const v0 = 1 - (y + 1) / gridH;
      const v1 = 1 - y / gridH;

      // Front Quad (+Z, norm 0,0,1) -> Group 1
      addQuad(
        frontPositions, frontNormals, frontUvs,
        [x0, y0, halfD], [x1, y0, halfD], [x1, y1, halfD], [x0, y1, halfD],
        [0, 0, 1],
        [u0, v0], [u1, v0], [u1, v1], [u0, v1]
      );

      // Back Quad (-Z, norm 0,0,-1) -> Group 2 (natural physical 3D mirrored rear view)
      addQuad(
        backPositions, backNormals, backUvs,
        [x1, y0, -halfD], [x0, y0, -halfD], [x0, y1, -halfD], [x1, y1, -halfD],
        [0, 0, -1],
        [u1, v0], [u0, v0], [u0, v1], [u1, v1]
      );

      // Perimeter Rim Quads -> Group 0 (3D Thickness following exact silhouette!)
      // Left Edge (-X)
      if (x === 0 || !mask[y * gridW + (x - 1)]) {
        addQuad(
          rimPositions, rimNormals, rimUvs,
          [x0, y0, -halfD], [x0, y0, halfD], [x0, y1, halfD], [x0, y1, -halfD],
          [-1, 0, 0],
          [0, 0], [1, 0], [1, 1], [0, 1]
        );
      }
      // Right Edge (+X)
      if (x === gridW - 1 || !mask[y * gridW + (x + 1)]) {
        addQuad(
          rimPositions, rimNormals, rimUvs,
          [x1, y0, halfD], [x1, y0, -halfD], [x1, y1, -halfD], [x1, y1, halfD],
          [1, 0, 0],
          [0, 0], [1, 0], [1, 1], [0, 1]
        );
      }
      // Bottom Edge (-Y)
      if (y === gridH - 1 || !mask[(y + 1) * gridW + x]) {
        addQuad(
          rimPositions, rimNormals, rimUvs,
          [x0, y0, -halfD], [x1, y0, -halfD], [x1, y0, halfD], [x0, y0, halfD],
          [0, -1, 0],
          [0, 0], [1, 0], [1, 1], [0, 1]
        );
      }
      // Top Edge (+Y)
      if (y === 0 || !mask[(y - 1) * gridW + x]) {
        addQuad(
          rimPositions, rimNormals, rimUvs,
          [x0, y1, halfD], [x1, y1, halfD], [x1, y1, -halfD], [x0, y1, -halfD],
          [0, 1, 0],
          [0, 0], [1, 0], [1, 1], [0, 1]
        );
      }
    }
  }

  const rimCount = rimPositions.length / 3;
  const frontCount = frontPositions.length / 3;
  const backCount = backPositions.length / 3;

  const allPos = new Float32Array(rimPositions.concat(frontPositions, backPositions));
  const allNorm = new Float32Array(rimNormals.concat(frontNormals, backNormals));
  const allUv = new Float32Array(rimUvs.concat(frontUvs, backUvs));

  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.BufferAttribute(allPos, 3));
  geo.setAttribute('normal', new THREE.BufferAttribute(allNorm, 3));
  geo.setAttribute('uv', new THREE.BufferAttribute(allUv, 2));

  // Multi-material groups:
  // Material 0: Rim / Edge thickness
  // Material 1: Front logo face
  // Material 2: Back logo face
  geo.addGroup(0, rimCount, 0);
  geo.addGroup(rimCount, frontCount, 1);
  geo.addGroup(rimCount + frontCount, backCount, 2);

  return geo;
}
